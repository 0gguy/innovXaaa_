import { useId } from "react";
import type { DispatchAudience, DispatchDocument, DispatchDocumentFormat, DispatchQuery, DispatchScope, DispatchVariant, Meta } from "../api/types";
import { useI18n } from "../i18n/I18n";
import { buildDispatchQuery } from "../scenario/queries";
import type { IssueWeeks, NumericField, ScenarioState } from "../scenario/scenario";
import type { Selection } from "./Controls";
import { InfoButton } from "./InfoButton";
import { ApplyRow, PlanningHead } from "./PlanningParts";
import { ScenarioControls } from "./ScenarioControls";
import { EmptyPanel, ErrorPanel, LoadingPanel } from "./StatusPanel";
import { usePlanning } from "./usePlanning";

/*
 * Dispatch Brief: a DRAFT planning document generated by the backend (GET /dispatch-brief, format=text). It is shown
 * as inert text (never parsed or injected as HTML) and offered for download through the backend's own download=true
 * responses. Nothing is sent to anyone. The location is the dashboard's selected city / ward (no second selector).
 */

export interface DispatchApi {
  document: (query: DispatchQuery, format: DispatchDocumentFormat, signal?: AbortSignal) => Promise<DispatchDocument>;
  url: (query: DispatchQuery, format: "json" | DispatchDocumentFormat) => string;
}
interface Options {
  scope: DispatchScope;
  audience: DispatchAudience;
  variant: DispatchVariant;
}

export function DispatchBrief({ api, meta, selection, baseUrl }: { api: DispatchApi | null; meta: Meta; selection: Selection; baseUrl: string }) {
  const { t, city: cityName, ward: wardName } = useI18n();
  const d = t.dispatch;
  const ids = { scope: useId(), audience: useId(), variant: useId() };
  const build = (s: ScenarioState, x: Options, w: IssueWeeks) =>
    buildDispatchQuery(s, w, {
      scope: x.scope,
      city: selection.city || undefined,
      wardId: x.scope === "ward" ? selection.ward || undefined : undefined,
      audience: x.audience,
      variant: x.variant,
    });
  const p = usePlanning<DispatchQuery, DispatchDocument, Options>({
    name: "dispatch",
    date: selection.date,
    weeks: meta.valid_issue_weeks,
    initialExtra: { scope: "city", audience: "all", variant: "detailed" },
    build,
    run: api ? (q, signal) => api.document(q, "text", signal) : null,
  });
  const withWeek = (s: ScenarioState): ScenarioState => ({ ...s, issueDate: selection.date || null });
  const draftNotCarried = build(withWeek(p.scenario.state), p.draftExtra, meta.valid_issue_weeks).notCarried;
  const appliedNotCarried = build(withWeek(p.appliedState), p.appliedExtra, meta.valid_issue_weeks).notCarried;
  const fieldName = (f: NumericField) => (f === "stockPctSaline" ? t.scenario.salineLabel : t.scenario.kitsLabel);
  const set = (patch: Partial<Options>) => p.setDraftExtra({ ...p.draftExtra, ...patch });

  return (
    <section className="planning" aria-labelledby="dispatch-title" aria-busy={p.req.status === "loading"}>
      <PlanningHead id="dispatch-title" title={d.title} date={selection.date} lead={d.lead} hypothetical={d.hypothetical} meta={meta} />

      <div className="planning-options" role="group" aria-label={d.optionsLabel}>
        <div className="field">
          <label htmlFor={ids.scope}>{d.scopeLabel}</label>
          <select id={ids.scope} value={p.draftExtra.scope} onChange={(e) => set({ scope: e.target.value === "ward" ? "ward" : "city" })}>
            <option value="city">{d.scopeCity(selection.city ? cityName(selection.city) : "—")}</option>
            <option value="ward">{d.scopeWard(selection.ward ? wardName(selection.ward) : "—")}</option>
          </select>
        </div>
        <div className="field">
          <label htmlFor={ids.audience}>{d.audienceLabel}</label>
          <select
            id={ids.audience}
            value={p.draftExtra.audience}
            onChange={(e) => set({ audience: e.target.value === "resource" ? "resource" : e.target.value === "hospital" ? "hospital" : "all" })}
          >
            <option value="all">{d.audienceAll}</option>
            <option value="resource">{d.audienceResource}</option>
            <option value="hospital">{d.audienceHospital}</option>
          </select>
        </div>
        <div className="field">
          <label htmlFor={ids.variant}>{d.variantLabel}</label>
          <select id={ids.variant} value={p.draftExtra.variant} onChange={(e) => set({ variant: e.target.value === "short" ? "short" : "detailed" })}>
            <option value="detailed">{d.variantDetailed}</option>
            <option value="short">{d.variantShort}</option>
          </select>
        </div>
        <p className="weekly-note">{d.locationNote}</p>
      </div>

      <ScenarioControls scenario={p.scenario} groups={["supplies", "crews", "hospital", "intervention"]} />
      {draftNotCarried.length > 0 && (
        <p className="planning-warning" data-testid="not-carried-draft">
          {d.notCarried(draftNotCarried.map(fieldName).join(", "))}
        </p>
      )}

      <ApplyRow
        label={d.generate}
        infoLabel={d.generateInfoLabel}
        infoBody={d.generateInfoBody}
        onApply={p.apply}
        disabled={!api || !selection.date}
        draftChanged={p.draftChanged}
        blocked={p.blocked}
        draftText={d.draftChanged}
      />

      {!api && <EmptyPanel title={t.planning.unavailableTitle} body={t.planning.unavailableBody} />}
      {api && !selection.date && <EmptyPanel title={t.planning.noWeekTitle} body={t.planning.noWeekBody} />}
      {api && selection.date && !p.appliedQuery.ok && <EmptyPanel title={d.invalidAppliedTitle} body={d.invalidAppliedBody} />}
      {p.req.status === "loading" && <LoadingPanel label={d.loading} />}
      {p.req.status === "error" && p.req.error && <ErrorPanel error={p.req.error} baseUrl={baseUrl} onRetry={p.req.reload} />}
      {p.req.status === "success" && p.req.data && p.appliedQuery.ok && api && (
        <div className="planning-results">
          <p className="planning-draft-label" data-testid="draft-label">
            <strong>{d.draftLabel}</strong> {d.draftStatement}
          </p>
          {appliedNotCarried.length > 0 && (
            <p className="planning-warning" data-testid="not-carried-applied">
              {d.notCarried(appliedNotCarried.map(fieldName).join(", "))}
            </p>
          )}
          <section className="planning-block" aria-labelledby="dispatch-preview-title">
            <div className="planning-block-head">
              <h3 id="dispatch-preview-title">{d.previewTitle}</h3>
              <InfoButton label={d.previewInfoLabel} title={d.previewTitle} description={d.previewInfoBody} />
            </div>
            <p className="weekly-note">{d.previewLanguage}</p>
            <pre className="dispatch-preview" lang="en" tabIndex={0} aria-labelledby="dispatch-preview-title" data-testid="brief-text">
              {p.req.data.body}
            </pre>
          </section>
          <section className="planning-block" aria-labelledby="dispatch-download-title">
            <h3 id="dispatch-download-title">{d.downloadTitle}</h3>
            <div className="dispatch-downloads">
              <div className="action-with-info">
                <a className="btn btn-quiet" href={api.url({ ...p.appliedQuery.query, download: true }, "text")} download>
                  {d.downloadText}
                </a>
                <InfoButton label={d.downloadTextInfoLabel} title={d.downloadText} description={d.downloadTextInfoBody} />
              </div>
              <div className="action-with-info">
                <a className="btn btn-quiet" href={api.url({ ...p.appliedQuery.query, download: true }, "html")} download>
                  {d.downloadHtml}
                </a>
                <InfoButton label={d.downloadHtmlInfoLabel} title={d.downloadHtml} description={d.downloadHtmlInfoBody} />
              </div>
            </div>
          </section>
        </div>
      )}
    </section>
  );
}
